                    Bit(Reaction.CataloguesYourCoat(outcome)));
                Row(sb, "IsPublicEvent", outcome.ToString(),
                    Bit(Reaction.IsPublicEvent(outcome)));
            }
            Row(sb, "ReactionConst", "ResistPressure", D(Reaction.ResistPressure));
        }

