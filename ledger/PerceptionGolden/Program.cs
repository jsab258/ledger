        // ---------------------------------------------------------------
        // THE CRIME SLICE, ruled 2026-09-08 (section 1 of
        // game-design/decision-2026-09-08-the-crime-the-witness-and-the-
        // overheard-consequence.md). Every row below is emitted BY THE REAL
        // CORE: the C++ transliteration in ue-probe answers the same rows
        // and the two must agree. Nothing here computes an expectation by
        // hand, because a hand-typed expectation would only prove that the
        // hand and the port agree.
        //
        // NO VALUE MAY CONTAIN A SPACE, A NEWLINE OR A PIPE. Every reader on
        // both sides splits on a delimiter and truncates silently when one
        // appears, so strings travel escaped: space as ~, newline as ^, pipe
        // as !. The C++ Escape in CoreGolden.h is the same three
        // substitutions and a dropped carriage return.
        static string Esc(string s)
        {
            if (s == null) return "null";
            var sb = new StringBuilder();
            foreach (var c in s)
            {
                if (c == ' ') sb.Append('~');
                else if (c == '\n') sb.Append('^');
                else if (c == '\r') { }
                else if (c == '|') sb.Append('!');
                else sb.Append(c);
            }
            return sb.ToString();
        }
        static string Unesc(string s)
        {
            var sb = new StringBuilder();
            foreach (var c in s)
            {
                if (c == '~') sb.Append(' ');
                else if (c == '^') sb.Append('\n');
                else if (c == '!') sb.Append('|');
                else sb.Append(c);
            }
            return sb.ToString();
        }
        static string Bit(bool b) => b ? "1" : "0";

        static void Row(StringBuilder sb, params string[] parts)
        {
            sb.Append(string.Join("|", parts)).Append('\n');
        }

        /// THE ARREST, 22 September. ROADMAP's stage-3 gate: "arrest reachable
        /// from live play, its callers outside Core counted and printed rather
        /// than zero". The Unreal port had no arrest at all, so these rows are
        /// what make a port of it checkable rather than merely written.
        ///
        /// EVERY INPUT CONFRONT READS, exhaustively where it is small: the slot
        /// set (five of them, including one without the Actor slot and one with
        /// every slot, so "Has(Actor)" is tested among other flags and not only
        /// alone), every rung from 0 to 6 across the boundary at 4, both
        /// answers to "does the player resist", and the constable who saw
        /// nothing at all. Then the two predicates over every outcome, and the
        /// one constant.
        static void EmitArrest(StringBuilder sb)
        {
            var slotSets = new[] { Slot.None, Slot.Actor, Slot.Act | Slot.Victim,
                                   Slot.Act | Slot.Actor | Slot.Victim,
                                   Slot.Precursor | Slot.Draw | Slot.Act | Slot.Victim
                                   | Slot.Actor | Slot.Flight | Slot.Aftermath };
            foreach (var slots in slotSets)
                for (int rung = 0; rung <= 6; rung++)
                    foreach (var resists in new[] { false, true })
                    {
                        var view = new Observation { Slots = slots, Rung = rung };
                        Row(sb, "Confront", ((int)slots).ToString(Inv), rung.ToString(Inv),
                            Bit(resists), Reaction.Confront(view, resists).ToString());
                    }
            foreach (var resists in new[] { false, true })
                Row(sb, "Confront", "null", "0", Bit(resists),
                    Reaction.Confront(null, resists).ToString());

            foreach (Reaction.Lawful outcome in Enum.GetValues(typeof(Reaction.Lawful)))
            {
                Row(sb, "CataloguesYourCoat", outcome.ToString(),
                    Bit(Reaction.CataloguesYourCoat(outcome)));
                Row(sb, "IsPublicEvent", outcome.ToString(),
                    Bit(Reaction.IsPublicEvent(outcome)));
            }
            Row(sb, "ReactionConst", "ResistPressure", D(Reaction.ResistPressure));
        }

        /// THE REACTION LADDER AND DECISION 7 (a), 23 September: StreetVoice's
        /// Stance, GazeMetres, StoryThatShows and RemarkLedger, which the slice
        /// needs in the shipping engine. The grid carries both sides of every
        /// rung threshold, the coat's 0.12 and 0.7, the loyalty weights and the
        /// leash, with and without a story that shows and a remark already had.
        /// A story case is written out in its row - each rumour as
        /// subject:predicate:value:confidence:sensitive:indelible:suppressed,
        /// joined by ';' - so the port builds the same holder from the row.
        static void EmitStance(StringBuilder sb)
        {
            var sus = new[] { 0.0, 0.21, 0.22, 0.47, 0.48, 0.4910, 0.5, 0.5455, 0.76, 0.77, 1.0 };
            var loys = new[] { 0.1, 0.5, 0.95, 1.0 };
            var ts = new[] { 0.0, 0.06, 0.07, 0.2, 0.3, 0.3111, 0.3556, 0.37, 0.38, 0.68, 0.69, 0.7, 0.7778, 1.0 };
            foreach (var s in sus)
                foreach (var loy in loys)
                    foreach (var t in ts)
                        foreach (var leash in new[] { false, true })
                            foreach (var coat in new[] { false, true })
                                foreach (var knows in new[] { false, true })
                                    foreach (var had in new[] { false, true })
                                        Row(sb, "Stance", D(s), D(loy), D(t), Bit(leash), Bit(coat), Bit(knows), Bit(had),
                                            StreetVoice.Stance(s, loy, t, leash, coat, knows, had).ToString());
            // ON EACH THRESHOLD AND ONE ROUNDING STEP EITHER SIDE, which the grid
            // alone never reached (an independent check planted '>' for '>='
            // at 0.12 and 0.42 and the grid passed it): suspicion alone for the
            // low rungs, suspicion 1 and a story for the high ones, and the
            // loyalty damping's 0.85 switch.
            foreach (var th in new[] { 0.12, 0.26, 0.42 })
            {
                double s0 = th / 0.55;
                foreach (var s in new[] { Math.BitDecrement(s0), s0, Math.BitIncrement(s0) })
                    foreach (var knows in new[] { false, true })
                        Row(sb, "Stance", D(s), D(0.5), D(0.0), "0", "0", Bit(knows), "0",
                            StreetVoice.Stance(s, 0.5, 0.0, false, false, knows, false).ToString());
            }
            foreach (var th in new[] { 0.58, 0.72, 0.85, 0.86 })
            {
                double t0 = (th - 0.55) / 0.45;
                foreach (var t in new[] { Math.BitDecrement(t0), t0, Math.BitIncrement(t0) })
                    foreach (var loy in new[] { 0.5, 0.6825868618354421 })
                        foreach (var leash in new[] { false, true })
                            Row(sb, "Stance", D(1.0), D(loy), D(t), Bit(leash), "0", "0", "0",
                                StreetVoice.Stance(1.0, loy, t, leash, false).ToString());
            }
            // the coat's 0.7, from a pressure a step either side of it
            foreach (var t in new[] { Math.BitDecrement((0.7 - 0.55) / 0.45), (0.7 - 0.55) / 0.45, Math.BitIncrement((0.7 - 0.55) / 0.45) })
                Row(sb, "Stance", D(1.0), D(0.5), D(t), "0", "1", "0", "0",
                    StreetVoice.Stance(1.0, 0.5, t, false, true).ToString());
            // THE REGRESSION ROW: the case /fp:fast turned from Refuses to Confronts.
            Row(sb, "Stance", D(0.9765076510350786), D(0.6825868618354421), D(0.8312113627658453), "0", "0", "0", "0",
                StreetVoice.Stance(0.9765076510350786, 0.6825868618354421, 0.8312113627658453, false, false).ToString());
            foreach (StanceKind k in Enum.GetValues(typeof(StanceKind)))
                Row(sb, "GazeMetres", k.ToString(), D(StreetVoice.GazeMetres(k)));

            string[][] cases =
            {
                new[] { "0.2", "player:night_walk:seen:0.3:1:0:0" },
                new[] { "0.2", "player:night_walk:seen:0.2:1:0:0" },
                new[] { "0.2", "player:night_walk:seen:0.19:1:0:0" },
                new[] { "0.2", "player:night_walk:seen:0.3:0:0:0" },
                new[] { "0.2", "player:night_walk:seen:0.9:1:0:1" },
                new[] { "0.2", "player:night_walk:seen:0.9:1:1:1" },
                new[] { "0.2", "rocco:night_walk:seen:0.9:1:0:0" },
                new[] { "0.2", "player:night_walk:seen:0.3:1:0:0;player:yard_visit:seen:0.6:1:0:0" },
                new[] { "0.2", "player:yard_visit:seen:0.6:0:0:0;player:night_walk:seen:0.3:1:0:0" },
                new[] { "0.5", "player:night_walk:seen:0.3:1:0:0" },
                new[] { "0.25", "player:night_walk:seen:0.3:1:0:0" },
                new[] { "0.2", "" },
                // ties keep the first; the stronger first; a suppressed stronger
                // story leaving the weaker to show
                new[] { "0.2", "player:night_walk:seen:0.4:1:0:0;player:yard_visit:seen:0.4:1:0:0" },
                new[] { "0.2", "player:yard_visit:seen:0.6:1:0:0;player:night_walk:seen:0.3:1:0:0" },
                new[] { "0.2", "player:yard_visit:seen:0.8:1:0:1;player:night_walk:seen:0.3:1:0:0" },
            };
            foreach (var c in cases)
            {
                var g = new Gossiper("h", "h", new MemoryStore("h"), new KnowledgeBase(), new SuspicionTracker());
                foreach (var enc in c[1].Split(new[] { ';' }, StringSplitOptions.RemoveEmptyEntries))
                {
                    var f = enc.Split(':');
                    var r = new Rumor
                    {
                        Content = new Fact(f[0], f[1], f[2]), OriginId = "o", Summary = "s",
                        Confidence = double.Parse(f[3], Inv), Sensitive = f[4] == "1", Indelible = f[5] == "1",
                    };
                    g.Rumors.Add(r);
                    if (f[6] == "1") g.Suppressed.Add(r.TopicKey);
                }
                var shows = StreetVoice.StoryThatShows(g, double.Parse(c[0], Inv));
                Row(sb, "StoryThatShows", c[0], c[1] == "" ? "none" : c[1],
                    (shows == null ? -1 : g.Rumors.IndexOf(shows)).ToString(Inv));
            }

            foreach (var (person, subj, pred, val) in new[] {
                ("m", "player", "informer", "rocco"), ("m", "player", "informer", "joey"),
                ("n", "player", "night_walk", "seen"), ("", "player", "killed", "") })
            {
                var r = new Rumor { Content = new Fact(subj, pred, val) };
                // THE KEY CARRIES THE TABLE'S OWN SEPARATOR, so '|' is written '#'.
                Row(sb, "RemarkKey", person == "" ? "none" : person, subj, pred, val == "" ? "none" : val,
                    RemarkLedger.KeyFor(person, r).Replace('|', '#'));
            }
            foreach (StanceKind k in Enum.GetValues(typeof(StanceKind)))
                foreach (var heard in new[] { false, true })
                {
                    var led = new RemarkLedger();
                    var r = new Rumor { Content = new Fact("player", "night_walk", "seen") };
                    var recorded = led.Record("m", r, k, heard);
                    // recorded, then whether it now reads as had: two bits, one answer
                    Row(sb, "RemarkRecord", k.ToString(), Bit(heard), Bit(recorded) + Bit(led.HasRemarked("m", r)));
                }
            {
                // ONCE: the same heard remark recorded twice records once.
                var led = new RemarkLedger();
                var r = new Rumor { Content = new Fact("player", "night_walk", "seen") };
                bool first = led.Record("m", r, StanceKind.Comments, true);
                bool second = led.Record("m", r, StanceKind.Comments, true);
                Row(sb, "RemarkRecordTwice", "Comments", "1", Bit(first) + Bit(second));
            }
        }

        /// KNOWING A LITTLE SHOWS, 28 September (Jafar's town list, item 1):
        /// StreetVoice's StoryHalfRemembered, Stance's knowsALittle floor, the
        /// look (FirstLookMetres, LookHoldSeconds, SecondLookMetres,
        /// LookAwayMetres, LooksBack and their constants), the faint remark
        /// (FaintDraw, MayRemarkFaintly,
        /// FaintRemark's lines, RemarkLedger.RecordFaint) and RegardFor, the
        /// one call the street makes. Holders are written as EmitStance's are.
        static void EmitKnowing(StringBuilder sb)
        {
            Gossiper HolderOf(string id, string enc, bool leashed = false, double suspicion = 0.0, double loyalty = 0.5)
            {
                var g = new Gossiper(id, id, new MemoryStore(id), new KnowledgeBase(), new SuspicionTracker(), loyalty: loyalty);
                g.Leashed = leashed;
                if (suspicion > 0) g.Suspicion.Raise(suspicion, "golden");
                foreach (var e in enc.Split(new[] { ';' }, StringSplitOptions.RemoveEmptyEntries))
                {
                    var f = e.Split(':');
                    var r = new Rumor
                    {
                        Content = new Fact(f[0], f[1], f[2]), OriginId = "o", Summary = "s",
                        Confidence = double.Parse(f[3], Inv), Sensitive = f[4] == "1", Indelible = f[5] == "1",
                    };
                    g.Rumors.Add(r);
                    if (f[6] == "1") g.Suppressed.Add(r.TopicKey);
                }
                return g;
            }
            string[] stories =
            {
                "", "player:night_walk:seen:0.1:1:0:0", "player:night_walk:seen:0.19:1:0:0",
                "player:night_walk:seen:0.2:1:0:0", "player:night_walk:seen:0.3:1:0:0",
                "player:night_walk:seen:0.0:1:0:0", "player:night_walk:seen:0.1:0:0:0",
                "player:night_walk:seen:0.05:1:0:1", "player:night_walk:seen:0.05:1:1:1",
                "rocco:night_walk:seen:0.1:1:0:0",
                "player:night_walk:seen:0.05:1:0:0;player:yard_visit:seen:0.15:1:0:0",
                "player:yard_visit:seen:0.15:1:0:0;player:night_walk:seen:0.15:1:0:0",
                "player:yard_visit:seen:0.3:1:0:0;player:night_walk:seen:0.1:1:0:0",
                // street talk about him, strong but not his nights; a NaN listed first
                "player:seen_about:quay:0.9:0:0:0",
                "player:seen_about:quay:NaN:1:0:0;player:seen_about:yard:0.9:1:0:0",
            };
            foreach (var floor in new[] { "0.2", "0.25" })
                foreach (var s in stories)
                {
                    var g = HolderOf("h", s);
                    var half = StreetVoice.StoryHalfRemembered(g, double.Parse(floor, Inv));
                    Row(sb, "StoryHalfRemembered", floor, s == "" ? "none" : s,
                        (half == null ? -1 : g.Rumors.IndexOf(half)).ToString(Inv));
                }

            foreach (var s in new[] { 0.0, 0.2, 0.22, 0.5, 1.0 })
                foreach (var loy in new[] { 0.1, 0.5, 0.95 })
                    foreach (var t in new[] { 0.0, 0.1, 0.19, 0.3, 0.7 })
                        foreach (var leash in new[] { false, true })
                            foreach (var coat in new[] { false, true })
                                foreach (var knows in new[] { false, true })
                                    foreach (var had in new[] { false, true })
                                        foreach (var little in new[] { false, true })
                                            Row(sb, "StanceLittle", D(s), D(loy), D(t), Bit(leash), Bit(coat), Bit(knows), Bit(had), Bit(little),
                                                StreetVoice.Stance(s, loy, t, leash, coat, knows, had, little).ToString());

            foreach (StanceKind k in Enum.GetValues(typeof(StanceKind)))
            {
                double hold = StreetVoice.LookHoldSeconds(k);
                Row(sb, "FirstLookMetres", k.ToString(), D(StreetVoice.FirstLookMetres(k)));
                Row(sb, "LookHoldSeconds", k.ToString(), double.IsPositiveInfinity(hold) ? "inf" : D(hold));
                Row(sb, "SecondLookMetres", k.ToString(), D(StreetVoice.SecondLookMetres(k)));
                Row(sb, "LookAwayMetres", k.ToString(), D(StreetVoice.LookAwayMetres(k)));
                Row(sb, "LooksBack", k.ToString(), Bit(StreetVoice.LooksBack(k)));
            }
            Row(sb, "StreetVoiceConst", "CivilGlanceMetres", D(StreetVoice.CivilGlanceMetres));
            Row(sb, "StreetVoiceConst", "CivilGlanceSeconds", D(StreetVoice.CivilGlanceSeconds));
            Row(sb, "StreetVoiceConst", "PassingZoneMetres", D(StreetVoice.PassingZoneMetres));
            Row(sb, "StreetVoiceConst", "KnowingLookSeconds", D(StreetVoice.KnowingLookSeconds));
            Row(sb, "StreetVoiceConst", "CivilLookAwayMetres", D(StreetVoice.CivilLookAwayMetres));

            // The draw over many people, so a port whose hash or modulo slips
            // by one lands on a different row somewhere.
            for (int i = 0; i < 40; i++)
            {
                string person = "p" + i.ToString(Inv);
                var r = new Rumor { Content = new Fact("player", "night_walk", "seen"), Confidence = 0.1 };
                string key = RemarkLedger.KeyFor(person, r);
                Row(sb, "FaintDraw", key.Replace('|', '#'), D(StreetVoice.FaintDraw(key)));
                foreach (var conf in new[] { 0.0, 0.05, 0.1, 0.19, 0.2 })
                {
                    r.Confidence = conf;
                    Row(sb, "MayRemarkFaintly", person, D(conf), "0.2", Bit(StreetVoice.MayRemarkFaintly(person, r, 0.2)));
                }
            }
            Row(sb, "MayRemarkFaintly", "none", "0.1", "0.2", Bit(StreetVoice.MayRemarkFaintly("x", null, 0.2)));
            Row(sb, "MayRemarkFaintly", "p0", "0.1", "0", Bit(StreetVoice.MayRemarkFaintly("p0",
                new Rumor { Content = new Fact("player", "night_walk", "seen"), Confidence = 0.1 }, 0.0)));
            // STRICTLY UNDER: a draw exactly equal to the share, and a hair over.
            foreach (var person in new[] { "p0", "p7", "resident7" })
            {
                var r = new Rumor { Content = new Fact("player", "night_walk", "seen") };
                double draw = StreetVoice.FaintDraw(RemarkLedger.KeyFor(person, r));
