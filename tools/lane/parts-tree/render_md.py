#!/usr/bin/env python3
"""Write production/lane/parts-tree/PARTS-TREE.md (the indented tree, phone-readable) from PARTS-TREE.json."""
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
D = os.path.join(ROOT, "production", "lane", "parts-tree")
doc = json.load(open(os.path.join(D, "PARTS-TREE.json"), encoding="utf-8"))
by = {p["id"]: p for p in doc["parts"]}
SHORT = {"missing": "missing", "designed": "designed", "built shallow": "shallow", "built": "built", "passes": "PASSES", "unknown": "?"}
L = ["# LEDGER parts tree", "",
     "The whole game as a multilevel parts list. Source of truth: PARTS-TREE.json (fields in README.md). Generated by tools/lane/parts-tree/render_md.py; do not edit by hand.", "",
     "Each line: id, name, then status as P (prototype) and U (Unreal): missing, designed, shallow (built shallow), built, PASSES, ? (no evidence). A star marks a part the player feels; 'research' marks a felt part whose standard is still to be measured.", ""]

def line(p):
    st = " ".join("%s:%s" % (t[0].upper(), SHORT[s["status"]]) for t, s in p["status"].items())
    star = "*" if p["felt"] else ""
    rn = " research" if p["research_items"] and not (p["standard"] and not p["standard"].lower().startswith("none")) else (" +research" if p["research_items"] else "")
    return "%s%s %s%s. %s%s" % ("  " * max(0, p["level"] - 1), p["id"], p["name"], star, st, rn)

def walk(pid):
    p = by[pid]
    if pid != "0":
        if p["level"] == 1:
            L.append(""); L.append("## " + p["id"] + " " + p["name"]); L.append("")
            L.append(p["what"]); L.append("")
        else:
            L.append("  " * (p["level"] - 2) + "- " + line(p).strip())
    for c in p["children"]:
        walk(c)
walk("0")
open(os.path.join(D, "PARTS-TREE.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("PARTS-TREE.md lines:", len(L))
